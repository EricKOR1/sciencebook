import puppeteer from 'puppeteer';
import fs from 'node:fs';
const [, , out, theme, fig, scale] = process.argv;
const b = await puppeteer.launch({ executablePath: fs.existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const p = await b.newPage(); await p.setViewport({ width: 1100, height: 900, deviceScaleFactor: +(scale||2) });
await p.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: theme }]);
await p.goto('file:///home/user/sciencebook/docs/umath-2.html', { waitUntil: 'load' });
await p.evaluate(() => document.querySelectorAll('details').forEach((d) => { d.open = true; }));
const el = await p.$('#fig-' + fig + ' .fig-art') || await p.$('#fig-' + fig);
await el.screenshot({ path: out });
await b.close();
